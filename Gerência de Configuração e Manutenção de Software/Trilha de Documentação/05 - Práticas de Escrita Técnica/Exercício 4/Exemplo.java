public class Exemplo {

    // Função que recebe dois números e retorna a soma
    public static int somar(int a, int b) {
        return a + b;
    }

    public static void main(String[] args) {

        int resultado = somar(5, 3);

        System.out.println(resultado);
    }
}

// public class Exemplo
// cria a classe principal do programa

// public static int somar(int a, int b)
// cria um método chamado somar
// int = tipo inteiro retornado

// return
// devolve o resultado da soma

// main
// ponto inicial da execução do programa

// int resultado
// armazena o valor retornado

